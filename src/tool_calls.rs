    #[test]
    fn typing_follows_the_declared_schema() {
        let schema = json!({
            "parameters": {"properties": {
                "path": {"type": "string"},
                "limit": {"type": "integer"},
                "deep": {"type": "boolean"},
                "opts": {"type": "object"}
            }}
        });
        let call = ParsedToolCall {
            name: "read".into(),
            parameters: vec![
                ("path".into(), "42".into()),
                ("limit".into(), "40".into()),
                ("deep".into(), "true".into()),
                ("opts".into(), "{\"a\": 1}".into()),
                ("extra".into(), "hello".into()),
            ],
        };
        let arguments = typed(&call.arguments_json(Some(&schema)));
        // A declared string stays a string even when it looks like a number.
        assert_eq!(arguments["path"], json!("42"));
        assert_eq!(arguments["limit"], json!(40));
        assert_eq!(arguments["deep"], json!(true));
        assert_eq!(arguments["opts"], json!({"a": 1}));
        // An undeclared parameter that is not JSON stays text.
        assert_eq!(arguments["extra"], json!("hello"));
        // The parameters keep the order the model wrote them in, which is part
        // of what the re-rendered prompt has to reproduce.
        assert!(
            arguments
                .as_object()
                .expect("an object")
                .keys()
                .eq(call.parameters.iter().map(|(name, _)| name))
        );
    }

